export function t(lang: string, key: string): string {
  let code = (lang || 'pl') as string;
  if (code === 'ru' || code === 'en-US' || code === 'en-GB') code = 'en';

  if (TRANSLATIONS[code] && TRANSLATIONS[code][key]) {
    return TRANSLATIONS[code][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  if (TRANSLATIONS['pl'] && TRANSLATIONS['pl'][key]) {
    return TRANSLATIONS['pl'][key];
  }
  return key;
}

