/**
 * Universal translation resolver for dynamic objects or inline bilingual text
 */
export function getText(lang: string, plText: string, enText: string, deText?: string): string {
  if (lang === 'pl') return plText;
  if (lang === 'en' || lang === 'en-US' || lang === 'en-GB') return enText;

  // Check custom dynamic fallbacks for language (e.g. ua, de, es, fr, etc.)
  if (DYNAMIC_FALLBACKS[lang]) {
    if (DYNAMIC_FALLBACKS[lang][plText]) return DYNAMIC_FALLBACKS[lang][plText];
    if (DYNAMIC_FALLBACKS[lang][enText]) return DYNAMIC_FALLBACKS[lang][enText];
  }

  // Check TRANSLATIONS key values reverse-match
  const code = (lang || 'en-US') as string;
  if (TRANSLATIONS[code]) {
    const plKeys = TRANSLATIONS['pl'] || {};
    const enKeys = TRANSLATIONS['en-US'] || {};
    for (const key of Object.keys(plKeys)) {
      if (plKeys[key] === plText || enKeys[key] === enText) {
        if (TRANSLATIONS[code][key]) {
          return TRANSLATIONS[code][key];
        }
      }
    }
  }

  if (deText && lang === 'de') return deText;

  return enText;
}
